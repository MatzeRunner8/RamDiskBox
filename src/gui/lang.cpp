void SetLanguage(const wchar_t* setting)
{
    rdb::Lang l = rdb::DefaultLanguage();
    if (setting) rdb::ParseLang(setting, l);   // "auto" oder Unbekanntes: Windows-Sprache
    rdb::SetProcessLanguage(l);
}

const wchar_t* T(Str id)
{
    if (id < 0 || id >= S_COUNT) return L"?";
    return rdb::En() ? kText[id].en : kText[id].de;
}
